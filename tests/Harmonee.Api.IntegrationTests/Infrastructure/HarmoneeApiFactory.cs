using Harmonee.SharedKernel;
using Harmonee.SharedKernel.AspNetCore;
using Microsoft.AspNetCore.Authentication;
using Microsoft.AspNetCore.Hosting;
using Microsoft.AspNetCore.Mvc.Testing;
using Microsoft.AspNetCore.TestHost;
using Microsoft.Data.SqlClient;
using Microsoft.Extensions.DependencyInjection;

namespace Harmonee.Api.IntegrationTests.Infrastructure;

/// <summary>
/// Runs the real API in memory against a real SQL Server database created for this test run.
/// SQL Server comes from HARMONEE_TEST_SQL (CI uses a SQL Server container) or LocalDB on Windows.
/// Authentication is replaced with a header-driven test scheme; authorization policies are the real ones.
/// </summary>
public sealed class HarmoneeApiFactory : WebApplicationFactory<Program>, IAsyncLifetime
{
    private const string LocalDb = "Server=(localdb)\\MSSQLLocalDB;Integrated Security=true;TrustServerCertificate=True";

    private readonly string _connectionString;
    private readonly string _databaseName = $"HarmoneeTests_{Guid.NewGuid():N}";

    public HarmoneeApiFactory()
    {
        var server = Environment.GetEnvironmentVariable("HARMONEE_TEST_SQL");
        var builder = new SqlConnectionStringBuilder(string.IsNullOrWhiteSpace(server) ? LocalDb : server)
        {
            InitialCatalog = _databaseName,
        };
        _connectionString = builder.ConnectionString;
    }

    protected override void ConfigureWebHost(IWebHostBuilder builder)
    {
        builder.UseEnvironment("Testing");
        builder.UseSetting($"ConnectionStrings:{ResourceNames.Database}", _connectionString);
        builder.UseSetting("AzureAd:Instance", "https://example.ciamlogin.com/");
        builder.UseSetting("AzureAd:TenantId", TestUser.TenantId);
        builder.UseSetting("AzureAd:ClientId", "00000000-0000-0000-0000-000000000001");

        builder.ConfigureTestServices(services =>
            services.AddAuthentication(options =>
                {
                    options.DefaultScheme = TestAuthHandler.SchemeName;
                    options.DefaultAuthenticateScheme = TestAuthHandler.SchemeName;
                    options.DefaultChallengeScheme = TestAuthHandler.SchemeName;
                })
                .AddScheme<AuthenticationSchemeOptions, TestAuthHandler>(TestAuthHandler.SchemeName, _ => { }));
    }

    public async ValueTask InitializeAsync()
    {
        await using var scope = Services.CreateAsyncScope();
        foreach (var migrator in scope.ServiceProvider.GetServices<IModuleMigrator>())
        {
            await migrator.MigrateAsync(CancellationToken.None);
        }
    }

    public HttpClient CreateClientFor(TestUser user)
    {
        var client = CreateClient();
        client.DefaultRequestHeaders.Add(TestAuthHandler.UserHeader, user.ObjectId);
        client.DefaultRequestHeaders.Add(TestAuthHandler.NameHeader, user.Name);
        if (user.IsPlatformAdmin)
        {
            client.DefaultRequestHeaders.Add(TestAuthHandler.AdminHeader, "true");
        }

        return client;
    }

    public override async ValueTask DisposeAsync()
    {
        await base.DisposeAsync();
        SqlConnection.ClearAllPools();

        var master = new SqlConnectionStringBuilder(_connectionString) { InitialCatalog = "master" }.ConnectionString;
        await using var connection = new SqlConnection(master);
        await connection.OpenAsync();
        await using var command = connection.CreateCommand();
#pragma warning disable CA2100 // The database name is generated by this class, not user input.
        command.CommandText = $"IF DB_ID('{_databaseName}') IS NOT NULL BEGIN ALTER DATABASE [{_databaseName}] SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE [{_databaseName}]; END";
#pragma warning restore CA2100
        await command.ExecuteNonQueryAsync();
    }
}

[CollectionDefinition(Name)]
public sealed class ApiTestGroup : ICollectionFixture<HarmoneeApiFactory>
{
    public const string Name = "api";
}
